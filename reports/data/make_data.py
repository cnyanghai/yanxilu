def write_csv(D, path):
    rows = []
    def add(sid, name, country, year, value, unit, source, category=""):
        if value is None: return
        rows.append([sid, name, country, year, category, value, unit, source])
    for i, y in enumerate(D["years"]):
        if i < len(D["cn_hh"]):
            add("hh_cons_gdp", "居民消费占GDP比重", "中国", y, D["cn_hh"][i], "%", "世界银行 NE.CON.PRVT.ZS")
            add("gcf_gdp", "资本形成占GDP比重", "中国", y, D["cn_gcf"][i], "%", "世界银行 NE.GDI.TOTL.ZS")
            add("gov_cons_gdp", "政府消费占GDP比重", "中国", y, D["cn_gov"][i], "%", "世界银行 NE.CON.GOVT.ZS")
            add("hh_cons_gdp", "居民消费占GDP比重", "美国", y, D["us_wb_hh"][i], "%", "世界银行 NE.CON.PRVT.ZS")
        add("pce_gdp_bea", "个人消费支出PCE占GDP比重（BEA最新修订）", "美国", y, D["us_hh"][i], "%", "BEA via FRED PCECA/GDPA")
        add("pce_services_share", "服务占PCE比重", "美国", y, D["us_svc"][i], "%", "BEA via FRED PCESVA/PCECA")
        add("pce_durable_share", "耐用品占PCE比重", "美国", y, D["us_dur"][i], "%", "BEA via FRED PCDGA/PCECA")
        add("pce_nondurable_share", "非耐用品占PCE比重", "美国", y, D["us_nd"][i], "%", "BEA via FRED PCNDA/PCECA")
        add("births", "出生人口", "中国", y, D["births"][i], "万人", "国家统计局 各年统计公报初值")
        add("deaths", "死亡人口", "中国", y, D["deaths"][i], "万人", "国家统计局 各年统计公报初值")
        a = D["age"].get(y)
        if a:
            src = "国家统计局 2026-01-19 人口数据解读" if y == 2025 else ("国家统计局《中国统计年鉴》人口年龄结构和抚养比" + ("（修订数）" if y >= 2013 else ""))
            add("pop_year_end", "年末总人口", "中国", y, a["pop"], "万人", src)
            for k, nm in (("c","0-14岁占比"),("w","15-64岁占比"),("o","65岁及以上占比"),("dep","总抚养比"),("depc","少儿抚养比"),("depo","老年抚养比")):
                add("age_"+k, nm, "中国", y, a[k], "%", src)
    for y, v in D["old60"].items():
        add("age_60plus", "60岁及以上占比", "中国", y, v, "%", "国家统计局 人口普查/统计公报")
    for y, v in D["engel_urban"].items(): add("engel_urban", "城镇居民恩格尔系数（旧口径）", "中国", y, v, "%", "《中国统计年鉴》")
    for y, v in D["engel_rural"].items(): add("engel_rural", "农村居民恩格尔系数（旧口径）", "中国", y, v, "%", "《中国统计年鉴》")
    for y, v in D["engel_nat"].items(): add("engel_national", "全国居民恩格尔系数（城乡一体化调查）", "中国", y, v, "%", "国家统计局")
    for y, v in D["cn_svc"].items(): add("services_share", "服务性消费支出占人均消费支出比重", "中国", y, v, "%", "国家统计局")
    for y in D["cn_amt"]:
        for j, c in enumerate(D["cats"]):
            add("pc_cons_amount", "全国居民人均消费支出（分类）", "中国", y, D["cn_amt"][y][j], "元", "国家统计局 居民收入和消费支出情况", c)
            add("pc_cons_share", "全国居民人均消费支出构成", "中国", y, D["cn_share"][y][j], "%", "国家统计局 居民收入和消费支出情况", c)
        add("pc_cons_total", "全国居民人均消费支出", "中国", y, D["cn_tot"][y], "元", "国家统计局 居民收入和消费支出情况")
    for r in D["us_cat"]:
        add("pce_cat_share", "PCE分项占比", "美国", 2000, r["v2000"], "%", "BEA via FRED", r["name"])
        add("pce_cat_share", "PCE分项占比", "美国", 2025, r["v2025"], "%", "BEA via FRED", r["name"])
    for name, v in D["intl"]:
        add("hh_cons_gdp", "居民消费占GDP比重", name, 2024, v, "%", "世界银行 NE.CON.PRVT.ZS")
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f); w.writerow(["series_id","series_name","country","year","category","value","unit","source"]); w.writerows(rows)
    print("CSV rows:", len(rows))

